import { FORK_ENABLED } from "@shared/fork/flags";
import type { ForkInfo } from "@shared/fork/types";
import { app } from "electron";
import { readFileSync } from "fs";
import { join } from "path";
import forkConfig from "../../../fork.config.json";
import forkBase from "../../../fork/upstream-base.json";
import { APP_VERSION } from "../version";

/**
 * Fork identity + startup self-check. Mounted once from `src/main/index.ts`
 * (`// FORK-MOUNT:M9`); every upstream file this fork touches is listed in
 * `fork/integration-points.md`.
 *
 * Sources of truth (all new files, never edited by an upstream sync):
 * - `fork.config.json` — who publishes this fork (owner/repo, product name);
 * - `fork/upstream-base.json` — which upstream tag/commit this fork sits on;
 * - `src/main/version.ts` (upstream) — the version compiled into this build.
 */

const PLACEHOLDER_PREFIX = "REPLACE_ME";

/** `true` while `fork.config.json` still holds the placeholder owner/repo. */
export function isForkConfigPlaceholder(): boolean {
  return (
    String(forkConfig.owner).startsWith(PLACEHOLDER_PREFIX) ||
    String(forkConfig.repo).startsWith(PLACEHOLDER_PREFIX)
  );
}

/**
 * Read the update feed compiled into the packaged app
 * (`resources/app-update.yml`, generated by electron-builder from the `publish`
 * block). Deliberately parsed by hand — the only two keys we need are flat
 * `owner:` / `repo:` scalars, and adding a YAML dependency to the runtime bundle
 * is not worth it.
 */
function readUpdateFeed(): ForkInfo["updateFeed"] {
  if (!app.isPackaged) return null;
  try {
    const text = readFileSync(
      join(process.resourcesPath, "app-update.yml"),
      "utf8",
    );
    const scalar = (key: string): string | null => {
      const match = new RegExp(`^\\s*${key}\\s*:\\s*(.+)$`, "m").exec(text);
      if (match === null) return null;
      return match[1].trim().replace(/^["']|["']$/g, "");
    };
    const owner = scalar("owner");
    const repo = scalar("repo");
    return owner !== null && repo !== null ? { owner, repo } : null;
  } catch {
    // No `app-update.yml` (build made without `publish`) — the updater reports
    // "unavailable" and nothing can overwrite this build.
    return null;
  }
}

let cachedFeed: ForkInfo["updateFeed"] | undefined;

/** A snapshot of the fork identity, served to the renderer via `fork:info`. */
export function getForkInfo(): ForkInfo {
  if (cachedFeed === undefined) cachedFeed = readUpdateFeed();
  const updateFeed = cachedFeed;
  return {
    appVersion: APP_VERSION,
    baseTag: forkBase.baseTag,
    baseCommit: forkBase.baseCommit,
    syncedAt: forkBase.syncedAt,
    updateFeed,
    updateFeedOk:
      updateFeed === null
        ? null
        : updateFeed.owner === forkConfig.owner &&
          updateFeed.repo === forkConfig.repo,
  };
}

/**
 * Startup self-check. The failure this guards against is the expensive one: a
 * build whose update feed still points at the official repo would offer
 * "updates" that silently replace this fork with an official build.
 */
export function initFork(): void {
  if (!FORK_ENABLED) return;

  if (isForkConfigPlaceholder()) {
    console.warn(
      "[fork] fork.config.json 仍为占位 owner/repo：更新源无法校验，发布前必须填好。",
    );
    return;
  }

  const info = getForkInfo();
  if (info.updateFeedOk === false && info.updateFeed !== null) {
    console.error(
      `[fork] 更新源指向 ${info.updateFeed.owner}/${info.updateFeed.repo}，` +
        `而本 fork 发布在 ${forkConfig.owner}/${forkConfig.repo}：` +
        "自动更新会把本 build 覆盖成别家的版本，请检查 electron-builder.fork.yml 的 publish。",
    );
  }
}
